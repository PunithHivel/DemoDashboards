    def import_jira_git_mappings(self, session: Session, mappings: List[Dict[str, Any]], org_id: int) -> Dict[str, Any]:
        """
        Import JIRA-Git activity mappings into insightly.jira_issue_git_activity_mapping table using high-performance COPY.
        Links Jira issues with Git activities (commits and pull requests).
        
        Note: 
        - 'id' is auto-generated by database sequence
        - 'activity_date' and 'actor' are fetched from commit/pull_request tables based on activity_id
        """
        try:
            if not mappings:
                return {"success": True, "inserted_count": 0}
            
            # Define columns for COPY (excluding auto-generated id)
            columns = [
                'issue_id', 'jira_issue_id', 'issue_key', 'activity_type',
                'activity_id', 'activity_date', 'actor', 'organization_id',
                'azure_issue_url', 'jira_hotfix_pr'
            ]
            
            # Collect all activity IDs by type for batch fetching
            commit_ids = []
            pr_ids = []
            for mapping in mappings:
                activity_type = mapping.get('activity_type')
                activity_id = mapping.get('activity_id')
                if activity_type in ['COMMIT', 'MERGE_COMMIT'] and activity_id:
                    # Convert to int if it's a string
                    commit_ids.append(int(activity_id) if isinstance(activity_id, str) else activity_id)
                elif activity_type == 'PULLREQUEST' and activity_id:
                    # Convert to int if it's a string
                    pr_ids.append(int(activity_id) if isinstance(activity_id, str) else activity_id)
            
            # Fetch commit data in batch
            commit_data = {}
            if commit_ids:
                commit_query = text("""
                    SELECT id, date, authorid 
                    FROM insightly.commit 
                    WHERE id = ANY(:ids) AND organizationid = :org_id
                """)
                result = session.execute(commit_query, {'ids': commit_ids, 'org_id': org_id})
                for row in result:
                    commit_data[row[0]] = {'date': row[1], 'authorid': row[2]}
            
            # Fetch pull request data in batch
            pr_data = {}
            if pr_ids:
                pr_query = text("""
                    SELECT id, createdon, authorid 
                    FROM insightly.pull_request 
                    WHERE id = ANY(:ids) AND organizationid = :org_id
                """)
                result = session.execute(pr_query, {'ids': pr_ids, 'org_id': org_id})
                for row in result:
                    pr_data[row[0]] = {'createdon': row[1], 'authorid': row[2]}
            
            # Prepare rows with fetched activity_date and actor
            rows = []
            skipped_count = 0
            for mapping in mappings:
                activity_type = mapping.get('activity_type')
                activity_id = mapping.get('activity_id')
                
                # Convert activity_id to int for lookup (CSV values are strings)
                activity_id_int = int(activity_id) if isinstance(activity_id, str) else activity_id
                
                # Fetch activity_date and actor based on activity_type
                activity_date = None
                actor = None
                
                if activity_type in ['COMMIT', 'MERGE_COMMIT']:
                    if activity_id_int in commit_data:
                        activity_date = commit_data[activity_id_int]['date']
                        actor = commit_data[activity_id_int]['authorid']
                    else:
                        skipped_count += 1
                        continue  # Skip if commit not found
                        
                elif activity_type == 'PULLREQUEST':
                    if activity_id_int in pr_data:
                        activity_date = pr_data[activity_id_int]['createdon']
                        actor = pr_data[activity_id_int]['authorid']
                    else:
                        skipped_count += 1
                        continue  # Skip if PR not found
                else:
                    skipped_count += 1
                    continue  # Skip invalid activity_type
                
                row = {
                    'issue_id': mapping.get('issue_id'),
                    'jira_issue_id': mapping.get('jira_issue_id'),
                    'issue_key': mapping.get('issue_key'),
                    'activity_type': activity_type,
                    'activity_id': activity_id,
                    'activity_date': activity_date,
                    'actor': actor,
                    'organization_id': org_id,
                    'azure_issue_url': mapping.get('azure_issue_url'),
                    'jira_hotfix_pr': mapping.get('jira_hotfix_pr')
                }
                rows.append(row)
            
            # Use bulk COPY for high-performance insert (insightly schema, not insightly_jira)
            from repositories.bulk_copy import bulk_copy_insert
            inserted_count = bulk_copy_insert(session, 'jira_issue_git_activity_mapping', columns, rows)
            
            session.commit()
            
            return {
                "success": True,
                "inserted_count": inserted_count,
                "skipped_count": skipped_count
            }
            
        except Exception as e:
            session.rollback()
            raise Exception(f"Error importing JIRA-Git mappings: {str(e)}")
