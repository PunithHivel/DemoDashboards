    def import_boards(self, session: Session, boards: List[Dict[str, Any]], org_id: int, user_integration_id: int = None) -> Dict[str, Any]:
        """
        Import boards into insightly_jira.board table
        Note: 'id' and 'created_at' are auto-generated by database
        """
        try:
            if not boards:
                return {"success": True, "inserted_count": 0, "inserted_records": []}
            
            inserted_records = []
            
            for board in boards:
                query = text("""
                    INSERT INTO insightly_jira.board (
                        account_id, active, avatar_uri, display_name, entity_id,
                        is_private, jira_board_id, board_key, name, org_id,
                        self, uuid, is_deleted, auto_generated_sprint, azure_project_id,
                        azure_project_name, azure_org_name, last_issue_update_time,
                        has_permission, valid, board_type, modifieddate
                    ) VALUES (
                        :account_id, :active, :avatar_uri, :display_name, :entity_id,
                        :is_private, :jira_board_id, :board_key, :name, :org_id,
                        :self, :uuid, :is_deleted, :auto_generated_sprint, :azure_project_id,
                        :azure_project_name, :azure_org_name, :last_issue_update_time,
                        :has_permission, :valid, :board_type, NOW()
                    )
                    RETURNING id, jira_board_id, name
                """)
                
                params = {
                    'account_id': board.get('account_id'),
                    'active': board.get('active'),
                    'avatar_uri': board.get('avatar_uri'),
                    'display_name': board.get('display_name'),
                    'entity_id': board.get('entity_id'),
                    'is_private': board.get('is_private'),
                    'jira_board_id': board.get('jira_board_id'),
                    'board_key': board.get('board_key'),
                    'name': board.get('name'),
                    'org_id': org_id,
                    'self': board.get('self'),
                    'uuid': board.get('uuid'),
                    'is_deleted': board.get('is_deleted', False),
                    'auto_generated_sprint': board.get('auto_generated_sprint', False),
                    'azure_project_id': board.get('azure_project_id'),
                    'azure_project_name': board.get('azure_project_name'),
                    'azure_org_name': board.get('azure_org_name'),
                    'last_issue_update_time': board.get('last_issue_update_time'),
                    'has_permission': board.get('has_permission'),
                    'valid': board.get('valid'),
                    'board_type': board.get('board_type')
                }
                
                result = session.execute(query, params)
                record = result.fetchone()
                if record:
                    inserted_records.append({
                        "id": record[0],
                        "jira_board_id": record[1],
                        "name": record[2]
                    })
            
            return {
                "success": True,
                "inserted_count": len(inserted_records),
                "inserted_records": inserted_records
            }
            
        except Exception as e:
            session.rollback()
            raise Exception(f"Error importing boards: {str(e)}")

