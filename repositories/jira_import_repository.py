    def import_issues(self, session: Session, issues: List[Dict[str, Any]], org_id: int, user_integration_id: int = None) -> Dict[str, Any]:
        """
        Import issues into insightly_jira.issue table using high-performance COPY.
        Note: 'id' and 'created_at' are auto-generated by database
        Only inserts columns that are provided in the CSV
        """
        try:
            if not issues:
                return {"success": True, "inserted_count": 0, "inserted_records": []}
            
            # Define columns for COPY (excluding auto-generated id and created_at)
            columns = [
                'modifieddate', 'board_id', 'sprint_id', 'issue_id', 'key',
                'issue_type', 'status', 'priority', 'story_point', 'summary',
                'assignee_id', 'is_deleted', 'is_epic', 'product', 'allocation',
                'jira_create_date', 'org_id', 'parent_issue_id'
            ]
            
            # Prepare rows with defaults and org_id
            rows = []
            for issue in issues:
                row = {
                    'modifieddate': 'NOW()',  # Will be handled specially
                    'board_id': issue.get('board_id'),
                    'sprint_id': issue.get('sprint_id') or None,
                    'issue_id': issue.get('issue_id'),
                    'key': issue.get('key'),
                    'issue_type': issue.get('issue_type'),
                    'status': issue.get('status'),
                    'priority': issue.get('priority'),
                    'story_point': issue.get('story_point'),
                    'summary': issue.get('summary'),
                    'assignee_id': issue.get('assignee_id'),
                    'is_deleted': 'false' if str(issue.get('is_deleted', 'False')).lower() == 'false' else 'true',
                    'is_epic': 'true' if str(issue.get('is_epic', 'False')).lower() == 'true' else 'false',
                    'product': issue.get('product', 'Unassigned'),
                    'allocation': issue.get('allocation', 'Unallocated'),
                    'jira_create_date': issue.get('jira_create_date'),
                    'org_id': org_id,
                    'parent_issue_id': issue.get('parent_issue_id') or None,
                }
                rows.append(row)
            
            # For COPY, we need to set modifieddate separately since NOW() is a function
            # Update modifieddate column to use current timestamp string
            from datetime import datetime
            current_time = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
            for row in rows:
                row['modifieddate'] = current_time
            
            # Use bulk COPY for high-performance insert
            inserted_count = bulk_copy_insert_jira(session, 'issue', columns, rows)
            
            session.commit()
            
            # Query back the inserted records to get their IDs
            query = text("""
                SELECT id, issue_id, "key" 
                FROM insightly_jira.issue 
                WHERE org_id = :org_id 
                ORDER BY id DESC 
                LIMIT :limit
            """)
            result = session.execute(query, {'org_id': org_id, 'limit': inserted_count})
            inserted_records = [
                {"id": row[0], "issue_id": row[1], "key": row[2]}
                for row in result.fetchall()
            ]
            inserted_records.reverse()  # Restore original order
            
            return {
                "success": True,
                "inserted_count": inserted_count,
                "inserted_records": inserted_records
            }
            
        except Exception as e:
            session.rollback()
            raise Exception(f"Error importing issues: {str(e)}")

